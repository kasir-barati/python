"""Generates compose.generated.yml: one worker service per pipeline YAML `workers` entry.

The pipeline YAML (name/location/class/instances) is the single source of truth for which worker
containers exist and how many replicas each runs; compose.yml only holds the static infra
(RabbitMQ, Postgres, pgAdmin). Run before `docker compose up`; see the `dev`/`down` Makefile targets.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).parent.parent
PIPELINE_YAML = REPO_ROOT / "src" / "pipelines" / "wiki_yahoo_scraper_pipeline.yaml"
OUTPUT_PATH = REPO_ROOT / "compose.generated.yml"


def _service_name(worker_name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "-", worker_name).lower()


def _service_for(worker: dict) -> dict:
    depends_on = {"rabbitmq": {"condition": "service_healthy"}}
    if worker["location"] == "workers.postgres":
        depends_on["postgres"] = {"condition": "service_healthy"}

    return {
        "build": ".",
        "command": ["uv", "run", "python", "-m", "run_worker"],
        # A stage with no input_queue is a one-shot producer (e.g. WikiWorker) and should not be
        # restarted on a clean exit; a consumer stage exits cleanly on idle timeout and should
        # only be restarted if it actually crashed.
        "restart": "on-failure" if "input_queue" in worker else "no",
        "env_file": [".env"],
        "environment": {"WORKER_NAME": worker["name"]},
        "depends_on": depends_on,
        "deploy": {"replicas": worker.get("instances", 1)},
    }


def main() -> None:
    with open(PIPELINE_YAML) as in_file:
        spec = yaml.safe_load(in_file)

    services = {_service_name(worker["name"]): _service_for(worker) for worker in spec["workers"]}

    with open(OUTPUT_PATH, "w") as out_file:
        out_file.write("# Generated by tools/render_compose.py from the pipeline YAML. Do not edit by hand.\n")
        yaml.safe_dump({"services": services}, out_file, sort_keys=False)


if __name__ == "__main__":
    main()
